# Is the Tonnetz kernel an ideal of Z[w]?  CM order of the Tonnetz torus.
import sympy as sp, json, math, itertools
res={}
# Eisenstein coordinates: fifth -> 1, major third -> 1+w (60 deg), so minor third -> -w ; pc map psi(a+b w)=7a+9b mod 12
psi=lambda a,b: (7*a+9*b)%12
res['psi(1)=7 fifth, psi(1+w)=4 M3, psi(-w)=3 m3']=(psi(1,0),psi(1,1),psi(0,-1))
# kernel basis: find lattice of (a,b) with psi=0
ker=[(a,b) for a in range(-12,13) for b in range(-12,13) if psi(a,b)==0]
# w*(a+bw) = -b + (a-b) w
stable=all(psi(-b,a-b)==0 for a,b in ker)
res['kernel_is_w_stable(ideal)']=stable
cex=next(((a,b),(-b,a-b),psi(-b,a-b)) for a,b in ker if psi(-b,a-b)!=0)
res['counterexample (z, w z, psi(wz))']=cex
# structural reason: Z[w]/I cyclic of order 12 would need x^2+x+1=0 mod 12 (also mod 2): none
res['roots_x2+x+1_mod_12']=[x for x in range(12) if (x*x+x+1)%12==0]
res['roots_mod_4']=[x for x in range(4) if (x*x+x+1)%4==0]
res['roots_mod_3']=[x for x in range(3) if (x*x+x+1)%3==0]
# ideals of norm 12 in Z[w]: 2*(1-w) up to units; quotient group structure
res['Z[w]/(2(1-w)) is Z2xZ2xZ3 (not cyclic) since (2) inert: F4 x F3']=True
# reduced kernel basis and shape tau
M=sp.Matrix([[a,b] for a,b in ker])
# HNF via sympy: lattice generated by (4,-4)? in fifth/M3 coords -> convert: Eisenstein a+bw with fifth=1, M3=1+w
# period vectors from winding.py: (4,-4) and (0,3) in (fifth,M3) coords => z = 4*1 -4*(1+w) = -4w ; 3*(1+w)
w=sp.Rational(-1,2)+sp.sqrt(3)*sp.I/2
P1=sp.nsimplify(-4*w); P2=sp.nsimplify(3*(1+w))
for z in (P1,P2):
    a=sp.re(z); b=sp.im(z)
res['periods']=[str(sp.simplify(P1)),str(sp.simplify(P2))]
# check periods map to 0 and index 12
res['periods_in_kernel']=(psi(0,-4)==0, psi(3,3)==0)
res['index']=abs(sp.Matrix([[0,-4],[3,3]]).det())
tau=sp.simplify(P2/P1)
res['tau=P2/P1']=str(sp.nsimplify(sp.simplify(sp.expand_complex(tau))))
x=sp.symbols('x')
mp_=sp.minimal_polynomial(sp.expand_complex(tau),x)
res['min_poly_tau']=str(mp_)
A_,B_,C_=sp.Poly(mp_,x).all_coeffs()
D=B_**2-4*A_*C_
res['discriminant']=int(D); res['conductor']=int(sp.sqrt(sp.Abs(D)/3))
# multiplier ring check: alpha=a+b w preserves kernel iff ... find minimal b>0
def preserves(a,b):
    # multiply z=c+dw by a+bw: (ac - bd) + (ad + bc - bd) w
    return all(psi(a*c-b*d, a*d+b*c-b*d)==0 for c,d in ker)
res['multiplier_ring_min_b']=min(b for b in range(1,25) for a in range(0,1) if preserves(a,b)) if any(preserves(0,b) for b in range(1,25)) else None
# class number of discriminant D by counting reduced primitive forms
def h(D):
    cnt=0; a=1
    while 3*a*a<=-D:
        for b in range(-a+1,a+1):
            if (b*b-D)%(4*a)==0:
                c=(b*b-D)//(4*a)
                if c>=a and math.gcd(math.gcd(a,abs(b)),c)==1 and not (b<0 and (a==c)):
                    cnt+=1
        a+=1
    return cnt
res['class_number_h(-432)']=h(int(D)); res['class_number_check_h(-3),h(-12),h(-48)']=(h(-3),h(-12),h(-48))
# j-invariant numeric
import mpmath as mp
mp.mp.dps=30
t=complex(sp.N(tau)); tt=mp.mpc(t.real,abs(t.imag))
res['j(tau)']=mp.nstr(1728*mp.kleinj(tt),25)
json.dump(res,open('eisenstein.json','w'),indent=1,default=str)
for k,v in res.items(): print(k,':',v)
